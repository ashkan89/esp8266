"""Rasterize the checked-in Lucide SVG assets to flash-resident OLED bitmaps.

Requires Pillow and developer-only @resvg/resvg-js (see the companion JS file).
Normal firmware builds need neither tool: include/oled_icons.h is committed.
"""
from pathlib import Path
import json
import subprocess
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parents[1]
subprocess.run(["node", str(root / "scripts/build_oled_icons.cjs")], check=True)
source = json.loads((root / "assets/oled/lucide/source.json").read_text(encoding="utf-8"))
lines = ["#pragma once", "#include <Arduino.h>", "// Generated by scripts/build_oled_icons.py; do not edit bitmap bytes.",
         "// Lucide/Feather attribution and licenses: assets/oled/lucide/LICENSE",
         "// Source commit: " + source["commit"], "namespace displayicons {"]
sheet = Image.new("RGB", (480, len(source["icons"]) * 76), "#101820")
draw = ImageDraw.Draw(sheet)
for i, name in enumerate(source["icons"]):
    draw.text((10, i*76+28), name, fill="white")
    for size in (12, 22):
        img = Image.open(root / f".pio/icon-tools/{name}-{size}.png").convert("RGBA")
        assert img.size == (size, size)
        mask = img.getchannel("A").point(lambda p: 255 if p >= 96 else 0)
        packed = []
        for y in range(size):
            for x in range(0, size, 8):
                value = sum((128 >> b) if x+b < size and mask.getpixel((x+b, y)) else 0 for b in range(8))
                packed.append(value)
        assert any(packed)
        symbol = name.replace("-", "_") + str(size)
        lines.append(f"const uint8_t {symbol}[] PROGMEM = {{" + ",".join(f"0x{v:02x}" for v in packed) + "};")
        rgb = Image.merge("RGB", (mask, mask, mask))
        sheet.paste(rgb.resize((size*3, size*3), Image.Resampling.NEAREST), (220 if size == 12 else 310, i*76+5))
lines.append("} // namespace displayicons")
(root / "include/oled_icons.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
sheet.save(root / ".pio/icon-tools/icon-sheet.png")
print("Generated", len(source["icons"])*2, "bitmap assets and icon preview")
